import assert from 'node:assert/strict';
import {parseListLine,formatCaptionList,continueCaptionList,normalizeCaptionLists} from './dist/caption-lists.js';
import {renderEventDescription} from './dist/event-content.js';
const edit=(text,line,command)=>{const start=text.split('\n').slice(0,line).join('\n').length+(line?1:0);return formatCaptionList(text,start,start,command).value;};
assert.equal(formatCaptionList('First\nSecond',0,12,'bullet').value,'- First\n- Second');
assert.equal(formatCaptionList('First\nSecond',0,12,'number').value,'1. First\n2. Second');
assert.equal(formatCaptionList('- First\n- Second',0,16,'bullet').value,'First\nSecond');
assert.equal(formatCaptionList('- First\n- Second',0,16,'number').value,'1. First\n2. Second');
assert.equal(formatCaptionList('First\nSecond',0,6,'bullet').value,'- First\nSecond');
let value='1. First\n2. Second\n3. Third';
value=edit(value,1,'indent');assert.equal(value,'1. First\n  1. Second\n2. Third');
value=edit(value,2,'indent');assert.equal(value,'1. First\n  1. Second\n  2. Third');
value=edit(value,2,'indent');assert.equal(value,'1. First\n  1. Second\n    1. Third');
assert.equal(edit(value,2,'indent'),value);
assert.equal(edit(value,0,'indent'),value);
assert.equal(edit(value,1,'indent'),value); // Moving its third-level child would exceed the cap.
assert.equal(edit(value,1,'outdent'),'1. First\n2. Second\n  1. Third');
assert.equal(edit(value,2,'outdent'),'1. First\n  1. Second\n  2. Third');
let enter=continueCaptionList('1. First',8,8);assert.equal(enter.value,'1. First\n2. ');assert.equal(enter.start,12);
enter=continueCaptionList(enter.value,enter.start,enter.end);assert.equal(enter.value,'1. First\n');
enter=continueCaptionList('- Parent\n  - Child',18,18);assert.equal(enter.value,'- Parent\n  - Child\n  - ');
enter=continueCaptionList(enter.value,enter.start,enter.end);assert.equal(enter.value,'- Parent\n  - Child\n- ');
assert.equal(continueCaptionList('Plain paragraph',5,5),null);
assert.equal(normalizeCaptionLists('9. One\n4. Two\nParagraph\n7. New'),'1. One\n2. Two\nParagraph\n1. New');
const html=renderEventDescription('### Day 1\n- **Parent**\n  1. Child\n    - ++Third++\n- Other\n\nNormal *text*.');
assert.equal(html,'<h3>Day 1</h3><ul><li><strong>Parent</strong><ol><li>Child<ul><li><u>Third</u></li></ul></li></ol></li><li>Other</li></ul><p>Normal <em>text</em>.</p>');
assert.equal(renderEventDescription('    - No parent\n      - Child'),'<ul><li>No parent<ul><li>Child</li></ul></li></ul>');
assert.ok(!renderEventDescription('- <img src=x onerror=alert(1)>').includes('<img'));
assert.equal(parseListLine('*Italic*'),null);
console.log('PASS: list toggles, numbering, three-level cap, subtree moves, Enter/exit, mixed rendering and safe formatting.');
